posicaoFinal = float(input("Digite a posição final: "))
posicaoInicial = float(input("Digite a posição inicial: "))
tempoFinal = float(input("Digite o tempo final: "))
tempoInicial = float(input("Digite o tempo inicial: "))

vm = (posicaoFinal - posicaoInicial)/(tempoFinal - tempoInicial)
print("A velocidade é:", vm )
